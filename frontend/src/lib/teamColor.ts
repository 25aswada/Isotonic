function lookupNcaaName(team: string) {
  const trimmed = team.trim()
  const variants = [
    trimmed,
    trimmed.replace(/\./g, ''),
    trimmed.replace(/ St$/, ' St.'),
    trimmed.replace(/ State$/, ' St.'),
    trimmed.replace(/ St\.$/, ' State'),
    trimmed.replace(/^Saint /, 'St. '),
    trimmed.replace(/^St /, 'St. '),
    trimmed.replace(/^St\. /, 'Saint '),
  ]

  for (const variant of variants) {
    if (ncaaNameColors[variant]) return ncaaNameColors[variant]
  }

  return undefined
}

export function teamAccent(team: string | null | undefined) {
  if (!team) return '#8da2ff'

  const cleaned = team.toUpperCase().trim()
  if (nbaColors[cleaned]) return nbaColors[cleaned]
  if (ncaaAbbrevColors[cleaned]) return ncaaAbbrevColors[cleaned]

  const aliasedTeam = ncaaAliases[cleaned]
  if (aliasedTeam) {
    const aliasColor = lookupNcaaName(aliasedTeam)
    if (aliasColor) return aliasColor
  }

  const nameColor = lookupNcaaName(team)
  if (nameColor) return nameColor

  const seed = Array.from(team).reduce((sum, character) => sum + character.charCodeAt(0), 0)
  const hue = seed % 360
  return `hsl(${hue} 78% 68%)`
}

